use std::fs;
use std::path::Path;

#[test]
fn every_installed_matma_rust_skill_contains_the_seven_rules_without_conflicting_legacy_guidance() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let platforms = ["claude", "chatgpt", "antigravity"];
    for platform in platforms {
        let base = root.join("integrations").join(platform).join("matma-rust");
        let path = base.join("SKILL.md");
        // Git on Windows checks out text files with CRLF; normalize the
        // skill content before validating portable Markdown frontmatter.
        let skill = fs::read_to_string(&path).expect("missing MATMA Rust skill")
            .replace("\r\n", "\n");
        let commands = fs::read_to_string(base.join("references/commands.md")).expect("missing bundled commands reference");
        assert!(skill.starts_with("---\nname: "), "{platform}: invalid skill frontmatter");
        assert_eq!(skill.matches("\n---\n").count(), 1, "{platform}: duplicate frontmatter/document");
        assert_eq!(skill.matches("## Seven architectural rules (required)").count(), 1);
        assert_eq!(skill.matches("## Mandatory development workflow").count(), 1);
        for rule in 1..=7 {
            assert!(skill.contains(&format!("### Rule {rule} —")), "{platform}: missing rule {rule}");
        }
        for phrase in [
            "real A and real B", "all other downstream collaborators",
            "tests/mocks/mirror/", "tests/business/", "tests/regression/",
            "per type", "mock", "Cargo executes tests",
            "references/commands.md", "stateful", "impl",
        ] {
            assert!(skill.contains(phrase), "{platform}: missing essential principle: {phrase}");
        }
        assert!(skill.contains("`#[cfg(test)]"), "{platform}: missing native private test bridge guidance");
        assert!(skill.contains("real concrete implementors"), "{platform}: missing trait contracts");
        for outdated in [
            "not generated by this CLI version",
            "external integration tests cannot inspect private",
            "cargo test --test matma_unit",
            "cargo test --test matma_interaction",
        ] {
            assert!(!skill.contains(outdated), "{platform}: outdated instruction: {outdated}");
        }
        assert!(commands.contains("matma-indexer context"), "{platform}: reference lacks current context command");
        assert!(commands.contains("matma-indexer changes"), "{platform}: reference lacks current changes command");
    }
}
