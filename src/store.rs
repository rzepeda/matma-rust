use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;
use std::time::UNIX_EPOCH;
use anyhow::{anyhow, bail, Context, Result};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use walkdir::WalkDir;
use crate::graph::Graph;
use crate::project::Project;
use crate::scaffold::Scaffold;
use crate::source_record::SourceRecord;

pub struct Store;
const HEADER: &str = "# Generated by MATMA Rust; DO NOT EDIT.\n";

impl Store {
    fn output(project: &Project, relative: &str, body: &str) -> Result<()> {
        let path = project.root.join(relative);
        if !path.starts_with(&project.tests_root) { bail!("unsafe index path {relative}"); }
        let mut parent = path.parent();
        while let Some(p) = parent {
            if p.is_symlink() { bail!("symlink in manifest output: {}", p.display()); }
            if p == project.root { break; }
            parent = p.parent();
        }
        if path.is_symlink() { bail!("symlink at manifest output {relative}"); }
        if path.exists() && !fs::read_to_string(&path)?.starts_with(HEADER) {
            bail!("refusing to overwrite non-MATMA manifest {relative}");
        }
        fs::create_dir_all(path.parent().unwrap())?;
        let value = format!("{HEADER}{body}");
        if path.exists() && fs::read_to_string(&path)? == value { return Ok(()); }
        let tmp = path.with_extension("auto.yaml.tmp");
        if tmp.exists() { bail!("temporary manifest path already exists: {}",tmp.display()); }
        fs::write(&tmp, value)?;
        if let Err(error) = fs::rename(&tmp, &path) {
            let _ = fs::remove_file(&tmp);
            return Err(error).context("atomic manifest replacement failed");
        }
        Ok(())
    }

    fn modified(path: &Path) -> Result<u64> {
        Ok(path.metadata()?.modified()?.duration_since(UNIX_EPOCH)?.as_nanos() as u64)
    }

    fn inventory(project: &Project) -> Result<(BTreeMap<String, String>, BTreeMap<String, u64>)> {
        let mut files = BTreeMap::new();
        let mut dirs = BTreeMap::new();
        for item in WalkDir::new(&project.source_root).follow_links(false).sort_by_file_name() {
            let entry = item?;
            if entry.file_type().is_symlink() { bail!("symlink inside Rust source root: {}",entry.path().display()); }
            let relative = project.relative(entry.path())?;
            if entry.file_type().is_dir() { dirs.insert(relative.clone(), Self::modified(entry.path())?); }
            if entry.file_type().is_file() && entry.path().extension().and_then(|v|v.to_str())==Some("rs") {
                let data = fs::read(entry.path())?;
                files.insert(relative, format!("{:x}", Sha256::digest(data)));
            }
        }
        Ok((files,dirs))
    }

    pub fn write(project: &Project, records: &[SourceRecord], graph: &Graph) -> Result<()> {
        let mut expected = BTreeSet::new();
        for record in records {
            let mirrors = Scaffold::mirror(project, record);
            let manifest_path = mirrors["manifest_file"].as_str().unwrap();
            expected.insert(manifest_path.to_string());
            let mut dependents: BTreeMap<String, Vec<Value>> = BTreeMap::new();
            for (file, level) in graph.dependents(&record.source_file) {
                if let Some(r) = records.iter().find(|r| r.source_file == file) {
                    dependents.entry(format!("level_{level}")).or_default().push(json!({
                        "symbol_name":r.symbol,"source_file":file,
                        "unit_test":Scaffold::mirror(project,r)["unit_test"],
                        "interaction_test":Scaffold::mirror(project,r)["interaction_test"]
                    }));
                }
            }
            let manifest = json!({
                "schema_version":1,"generator":"matma-rust", "symbol_name":record.symbol,
                "symbol_kind":record.kind,"identity":record.identity(),"source_file":record.source_file,"source_sha256":record.sha256,
                "mirrors":mirrors,"dependencies":graph.dependencies(&record.source_file,records),
                "dependents":dependents,"diagnostics":record.diagnostics,
            });
            Self::output(project, manifest_path, &serde_yaml::to_string(&manifest)?)?;
        }
        let (hashes, dirs) = Self::inventory(project)?;
        let source_root = project.relative(&project.source_root)?;
        let tests_root = project.relative(&project.tests_root)?;
        let symbols: Vec<_> = records.iter().map(|r| json!({
            "source_file":r.source_file,"symbol":r.symbol,"identity":r.identity(),
            "manifest":Scaffold::mirror(project,r)["manifest_file"]
        })).collect();
        let index = json!({"schema_version":1,"generator":"matma-rust","source_root":source_root,
            "tests_root":tests_root,"files":hashes,"directories":dirs,"symbols":symbols});
        let index_path = project.relative(&project.tests_root.join("mirror/.index.auto.yaml"))?;
        expected.insert(index_path.clone());
        // Remove only owned, obsolete generated manifests. Never delete authored files.
        let mirror_root = project.tests_root.join("mirror");
        if mirror_root.exists() {
            for entry in WalkDir::new(&mirror_root).follow_links(false) {
                let entry = entry?;
                if entry.file_type().is_symlink() { bail!("symlink in manifest directory"); }
                if !entry.file_type().is_file() || !entry.file_name().to_string_lossy().ends_with(".auto.yaml") { continue; }
                let path = project.relative(entry.path())?;
                if !expected.contains(&path) && fs::read_to_string(entry.path())?.starts_with(HEADER) {
                    fs::remove_file(entry.path())?;
                }
            }
        }
        Self::output(project, &index_path, &serde_yaml::to_string(&index)?)
    }

    pub fn read(project: &Project) -> Result<Value> {
        let path = project.tests_root.join("mirror/.index.auto.yaml");
        let index = Self::read_yaml(&path)?;
        if index["schema_version"] != 1 || index["generator"] != "matma-rust" { bail!("unsupported MATMA index schema"); }
        if index["source_root"].as_str() != Some(project.relative(&project.source_root)?.as_str())
            || index["tests_root"].as_str() != Some(project.relative(&project.tests_root)?.as_str()) {
            bail!("MATMA index configuration changed; run index");
        }
        // No AST parse, glob, or source tree traversal: only registered files
        // and directory metadata are verified. Source hashes make this O(N).
        let files = index["files"].as_object().ok_or_else(||anyhow!("invalid file inventory"))?;
        for (relative, original) in files {
            let current = fs::read(project.root.join(relative)).map(|d|format!("{:x}", Sha256::digest(d)))
                .unwrap_or_default();
            if original.as_str() != Some(current.as_str()) { bail!("stale MATMA index ({relative}); run index"); }
        }
        let dirs = index["directories"].as_object().ok_or_else(||anyhow!("invalid directory inventory"))?;
        for (relative, old) in dirs {
            let current = Self::modified(&project.root.join(relative)).unwrap_or(0);
            if old.as_u64() != Some(current) { bail!("stale MATMA index (directory {relative}); run index"); }
        }
        Ok(index)
    }

    pub fn read_yaml(path: &Path) -> Result<Value> {
        let content = fs::read_to_string(path).with_context(||format!("missing MATMA index {}; run index",path.display()))?;
        if !content.starts_with(HEADER) { bail!("unowned/corrupt MATMA index: {}",path.display()); }
        Ok(serde_yaml::from_str(&content)?)
    }
}
